CREATE TRIGGER finance_payment_commands_immutable_update BEFORE UPDATE ON finance_payment_commands FOR EACH ROW EXECUTE FUNCTION printora_finance_immutable();
DROP TRIGGER IF EXISTS finance_payment_commands_immutable_delete ON finance_payment_commands;
CREATE TRIGGER finance_payment_commands_immutable_delete BEFORE DELETE ON finance_payment_commands FOR EACH ROW EXECUTE FUNCTION printora_finance_immutable();
DROP TRIGGER IF EXISTS payment_refunds_immutable_update ON payment_refunds;
CREATE TRIGGER payment_refunds_immutable_update BEFORE UPDATE ON payment_refunds FOR EACH ROW EXECUTE FUNCTION printora_finance_immutable();
DROP TRIGGER IF EXISTS payment_refunds_immutable_delete ON payment_refunds;
CREATE TRIGGER payment_refunds_immutable_delete BEFORE DELETE ON payment_refunds FOR EACH ROW EXECUTE FUNCTION printora_finance_immutable();
DROP TRIGGER IF EXISTS payment_refund_allocations_immutable_update ON payment_refund_allocations;
CREATE TRIGGER payment_refund_allocations_immutable_update BEFORE UPDATE ON payment_refund_allocations FOR EACH ROW EXECUTE FUNCTION printora_finance_immutable();
DROP TRIGGER IF EXISTS payment_refund_allocations_immutable_delete ON payment_refund_allocations;
CREATE TRIGGER payment_refund_allocations_immutable_delete BEFORE DELETE ON payment_refund_allocations FOR EACH ROW EXECUTE FUNCTION printora_finance_immutable();
DROP TRIGGER IF EXISTS payment_disputes_no_delete ON payment_disputes;
